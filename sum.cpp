#include <iostream>
using namespace std; 

int main (){
    int x ;
    int y ;

    cout<<"Enter the first number :";
    cin>> x ;
    cout<<"Enter the second number :";
    cin>> y ;
    int sum = x + y ;
    cout<<"Sum :"<<sum<<endl;
    int sub = x - y ;
    cout<<"Sub :"<<sub<<endl;

    int mul = x * y;
    cout<<"Mul :"<<mul<<endl;

    float div = x / y ;
    cout<<"Div :"<<div<<endl;
    
}